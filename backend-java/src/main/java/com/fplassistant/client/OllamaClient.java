package com.fplassistant.client;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonProperty;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;
import org.springframework.web.client.RestTemplate;

import java.util.List;
import java.util.Map;

/**
 * HTTP Client connecting to local Ollama server.
 */
@Component
public class OllamaClient {

    private static final Logger log = LoggerFactory.getLogger(OllamaClient.class);

    private final RestTemplate restTemplate;

    @Value("${app.ollama.base-url:http://localhost:11434}")
    private String ollamaBaseUrl;

    @Value("${app.ollama.model:llama3.1:8b}")
    private String modelName;

    public OllamaClient(RestTemplate restTemplate) {
        this.restTemplate = restTemplate;
    }

    public String generateResponse(String systemPrompt, String userPrompt) {
        String url = ollamaBaseUrl + "/api/generate";
        log.info("Sending prompt to local Ollama model '{}' at {}", modelName, url);

        Map<String, Object> request = Map.of(
                "model", modelName,
                "system", systemPrompt,
                "prompt", userPrompt,
                "stream", false
        );

        try {
            OllamaGenerateResponse response = restTemplate.postForObject(url, request, OllamaGenerateResponse.class);
            return response != null && response.getResponse() != null ? response.getResponse() : "No response generated by Ollama.";
        } catch (Exception e) {
            log.warn("Ollama service unavailable at {}: {}. Falling back to default data narration.", url, e.getMessage());
            return null; // Signals fallback to deterministic narrative
        }
    }

    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class OllamaGenerateResponse {
        private String response;
        private Boolean done;

        public String getResponse() { return response; }
        public void setResponse(String response) { this.response = response; }

        public Boolean getDone() { return done; }
        public void setDone(Boolean done) { this.done = done; }
    }
}
